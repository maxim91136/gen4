/** Satz in einer Sprache, Platzhalter gefüllt. Fehlt etwas, fällt es auf statt still zu verschwinden. */
export function satz(sprache, schluessel, werte = {}) {
  const s = (TEXTE[sprache] || TEXTE.de)[schluessel];
  if (s === undefined) return '[' + schluessel + ']';
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in werte ? String(werte[k]) : '{' + k + '}'));
}
